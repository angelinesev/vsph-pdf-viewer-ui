/**
 * Writes apps/shared/config.js for local/Netlify deploys.
 * Uses env vars; falls back to this project's Supabase URL when unset.
 */
const fs = require('fs');
const path = require('path');

try {
  require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
} catch {
  /* optional */
}

const root = path.join(__dirname, '..');
const out = path.join(root, 'apps', 'shared', 'config.js');

const supabaseUrl =
  process.env.SUPABASE_URL
  || process.env.NEXT_PUBLIC_SUPABASE_URL
  || 'https://phftvaptlqibllkqcduf.supabase.co';

const supabaseAnonKey =
  process.env.SUPABASE_ANON_KEY
  || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
  || '';

let publicBaseUrl =
  process.env.PUBLIC_BASE_URL
  || process.env.BASE_URL
  || process.env.URL
  || 'https://vsph-pdfviewer.netlify.app';

if (publicBaseUrl.endsWith('/')) {
  publicBaseUrl = publicBaseUrl.slice(0, -1);
}

if (!supabaseAnonKey) {
  console.warn(
    '[write-portal-config] SUPABASE_ANON_KEY missing - portals will not auth until set.',
  );
}

if (!supabaseAnonKey && process.env.NETLIFY === 'true') {
  console.error('[write-portal-config] SUPABASE_ANON_KEY is required on Netlify.');
  process.exit(1);
}

const contents = [
  '/** Auto-generated by scripts/write-portal-config.js - do not edit by hand. */',
  'window.BROCHURE_SAAS = {',
  `  supabaseUrl: ${JSON.stringify(supabaseUrl)},`,
  `  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},`,
  '  // Same-origin Netlify/Express SaaS API (no Edge Function CORS)',
  '  functionsBase: "/api/saas",',
  `  publicBaseUrl: ${JSON.stringify(publicBaseUrl)},`,
  '};',
  '',
].join('\n');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, contents, 'utf8');
console.log('[write-portal-config] wrote', out);
